#simple list
mylist = ["apple", "banana", "cherry"]
#add one element at the end
mylist.append("orange")
print(mylist)
#add item by using index
mylist.insert(1, "kiwi")
print(mylist)
#remove an element using pop
mylist.pop(1)
print(mylist)
#reverse list
mylist.reverse()
print(mylist)
mylist.sort()
print(mylist)